#!/usr/bin/env node

import {
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export function releaseNodeVersion() {
  return readFileSync(join(root, ".node-version"), "utf8").trim();
}

export function assertReleaseNodeVersion() {
  const expected = releaseNodeVersion();
  if (process.versions.node !== expected) {
    throw new Error(
      `official binaries require Node.js ${expected}; current version is ${process.versions.node}`,
    );
  }
}

export function generateThirdPartyNotices() {
  assertReleaseNodeVersion();

  const nodeLicensePath = resolve(dirname(process.execPath), "..", "LICENSE");
  let nodeLicense;
  try {
    nodeLicense = readFileSync(nodeLicensePath, "utf8").trim();
  } catch {
    throw new Error(
      `Node.js LICENSE not found at ${nodeLicensePath}; build with the official Node.js ${releaseNodeVersion()} distribution`,
    );
  }

  const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
  const sections = [
    "THIRD-PARTY SOFTWARE NOTICES",
    "",
    "This file is generated by `npm run licenses`. Do not edit it manually.",
    "It covers the Node.js runtime and production npm packages distributed in",
    "the Situla single-executable binary. Situla itself is licensed separately",
    "under the Apache License 2.0 in LICENSE.",
    "",
    divider(),
    `Node.js v${process.versions.node}`,
    divider(),
    normalizedLicenseText(nodeLicense),
  ];

  const packages = Object.entries(lock.packages)
    .filter(([path, metadata]) => (
      path.startsWith("node_modules/")
      && !metadata.dev
      && !metadata.link
    ))
    .map(([path]) => {
      const packageDirectory = join(root, path);
      const metadata = JSON.parse(readFileSync(join(packageDirectory, "package.json"), "utf8"));
      const noticeFiles = readdirSync(packageDirectory)
        .filter((name) => /^(?:licen[cs]e|notice)(?:[._-].*)?$/i.test(name))
        .sort((left, right) => left.localeCompare(right));
      if (!noticeFiles.length) {
        throw new Error(`no license text found for ${metadata.name}@${metadata.version}`);
      }
      return {
        name: String(metadata.name),
        version: String(metadata.version),
        license: String(metadata.license ?? "SEE LICENSE TEXT"),
        notices: noticeFiles.map((name) => ({
          name,
          text: normalizedLicenseText(
            readFileSync(join(packageDirectory, name), "utf8").trim(),
          ),
        })),
      };
    })
    .sort((left, right) => left.name.localeCompare(right.name));

  for (const dependency of packages) {
    sections.push(
      "",
      divider(),
      `${dependency.name}@${dependency.version} (${dependency.license})`,
      divider(),
    );
    for (const notice of dependency.notices) {
      if (dependency.notices.length > 1) sections.push(`[${notice.name}]`, "");
      sections.push(notice.text);
    }
  }

  const output = `${sections.join("\n")}\n`;
  const outputPath = join(root, "THIRD_PARTY_NOTICES.txt");
  writeFileSync(outputPath, output);
  return { output, outputPath, packageCount: packages.length };
}

function divider() {
  return "=".repeat(79);
}

function normalizedLicenseText(value) {
  return value.replace(/^ +\t/gm, "\t");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = generateThirdPartyNotices();
  console.log(
    `Wrote ${result.packageCount} npm package notices to ${result.outputPath}`,
  );
}
